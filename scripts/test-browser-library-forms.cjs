/* eslint-disable @typescript-eslint/no-require-imports, @typescript-eslint/explicit-function-return-type */
const { launchQaBrowser } = require('./qa-browser.cjs')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await launchQaBrowser()
  try {
    for (const height of [900, 600]) {
      const page = await browser.newPage({ viewport: { width: 1400, height } })
      await page.goto(process.env.BROWSER_ORIGIN || process.env.CANVAS_QA_URL || 'http://127.0.0.1:5196')
      await page.waitForFunction(() => Boolean(window.api))
      await page.evaluate(async () => {
        window.api.listLibraryCategories = async () => ({ ok: true, data: [] })
        window.api.searchLibrary = async () => ({ ok: true, data: { items: [], nextCursor: null } })
        ;(await import('/src/stores/app.ts')).useAppStore.getState().setHome()
      })
      await page.getByRole('button', { name: '资源库', exact: true }).click()
      await page.locator('.library-resource-browser').waitFor()
      assert.equal(await page.locator('.library-empty-state').count(), 0)
      await page.getByRole('button', { name: '新建分类', exact: true }).click()
      const category = page.getByRole('dialog', { name: '资源分类编辑器' })
      const categoryName = category.getByLabel('分类名称', { exact: true })
      await categoryName.fill('测试分类')
      await categoryName.focus()
      await page.waitForTimeout(180)
      const fieldStyle = await categoryName.evaluate((element) => ({ border: getComputedStyle(element).borderColor, shadow: getComputedStyle(element).boxShadow }))
      assert.equal(fieldStyle.shadow, 'none')
      assert.equal(fieldStyle.border, 'rgb(105, 113, 125)')
      const mapping = category.getByRole('combobox', { name: '映射到节点' })
      await mapping.click()
      const text = page.getByRole('option', { name: '文本', exact: true })
      const hit = await text.evaluate((element) => {
        const box = element.getBoundingClientRect()
        const top = document.elementFromPoint(box.left + box.width / 2, box.top + box.height / 2)
        return Boolean(top && element.contains(top))
      })
      assert.equal(hit, true, '下拉选项在弹窗上方且可点击')
      await text.click()
      assert.match(await mapping.innerText(), /文本/)
      await mapping.focus()
      await page.keyboard.press('Enter')
      await page.getByRole('option', { name: '文本', exact: true }).waitFor()
      await page.keyboard.press('Escape')
      assert.equal(await mapping.getAttribute('data-state'), 'closed')
      await category.getByRole('button', { name: '关闭' }).click()
      await page.getByRole('button', { name: '新建资源', exact: true }).click()
      const form = page.getByRole('dialog', { name: '新建资源', exact: true })
      const resourceName = form.getByLabel('资源名称', { exact: true })
      await resourceName.fill('测试资源')
      await resourceName.focus()
      await page.waitForTimeout(180)
      const resourceStyle = await resourceName.evaluate((element) => ({ border: getComputedStyle(element).borderColor, shadow: getComputedStyle(element).boxShadow }))
      assert.deepEqual(resourceStyle, fieldStyle)
      await form.getByRole('combobox', { name: '资源分类' }).click()
      await page.getByRole('option', { name: '不选分类，保存为自由组合' }).click()
      assert.equal(await form.getByRole('combobox', { name: '资源分类' }).getAttribute('data-state'), 'closed')
      await page.close()
    }
    console.log('PASS resource library empty state, neutral focus and clickable modal dropdowns at both viewport heights')
  } finally {
    await browser.close()
  }
})().catch((error) => { console.error(error); process.exitCode = 1 })
